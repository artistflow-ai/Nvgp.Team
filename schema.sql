create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  category text default 'News',
  image_url text,
  body text not null,
  published boolean not null default false,
  author_id uuid references auth.users(id),
  created_at timestamptz not null default now()
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id),
  email text not null,
  service text not null,
  amount numeric(10,2) not null check (amount > 0),
  payment_provider text not null,
  provider_order_id text,
  status text not null default 'pending',
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.articles enable row level security;
alter table public.orders enable row level security;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;
create policy "profiles read own" on public.profiles for select using (id=auth.uid() or public.is_admin());
create policy "profiles update own safe" on public.profiles for update using (id=auth.uid()) with check (id=auth.uid() and role='user');
create policy "published articles public" on public.articles for select using (published=true or public.is_admin());
create policy "admin insert articles" on public.articles for insert with check (public.is_admin());
create policy "admin update articles" on public.articles for update using (public.is_admin()) with check (public.is_admin());
create policy "admin delete articles" on public.articles for delete using (public.is_admin());
create policy "orders read own or admin" on public.orders for select using (user_id=auth.uid() or public.is_admin());
-- Il client non può creare/modificare ordini direttamente: solo le Edge Functions con service role.
create policy "profiles insert self" on public.profiles for insert with check (id=auth.uid() and role='user');
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin insert into public.profiles(id,email,role) values(new.id,new.email,'user'); return new; end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
