-- NVGP.TEAM + NVGP STUDIO — Supabase schema
-- Run in Supabase SQL Editor. Review policies before production.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 email text, role text not null default 'user' check(role in ('user','admin')),
 created_at timestamptz not null default now()
);
create table if not exists public.articles (
 id bigint generated by default as identity primary key,
 title text not null, category text not null default 'Rap News',
 image_url text, description text not null default '', body text not null,
 published boolean not null default false, author_id uuid references auth.users(id),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 user_id uuid references auth.users(id), email text not null, service text not null,
 amount numeric(10,2) not null check(amount>0), payment_provider text not null,
 provider_order_id text, status text not null default 'pending', created_at timestamptz not null default now()
);
create table if not exists public.studio_sessions (
 id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
 name text not null, session_type text not null check(session_type in ('mix','master','mix-master')),
 notes text default '', status text not null default 'draft',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.studio_tracks (
 id uuid primary key default gen_random_uuid(), session_id uuid not null references public.studio_sessions(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade, storage_path text not null,
 file_name text not null, mime_type text, size_bytes bigint, created_at timestamptz not null default now()
);
create table if not exists public.studio_outputs (
 id uuid primary key default gen_random_uuid(), session_id uuid not null references public.studio_sessions(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade, storage_path text not null,
 format text, version integer not null default 1, created_at timestamptz not null default now()
);
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;
alter table public.profiles enable row level security;
alter table public.articles enable row level security;
alter table public.orders enable row level security;
alter table public.studio_sessions enable row level security;
alter table public.studio_tracks enable row level security;
alter table public.studio_outputs enable row level security;
drop policy if exists "profiles read own" on public.profiles;
create policy "profiles read own" on public.profiles for select using(id=auth.uid() or public.is_admin());
drop policy if exists "profiles insert self" on public.profiles;
create policy "profiles insert self" on public.profiles for insert with check(id=auth.uid() and role='user');
drop policy if exists "profiles update own safe" on public.profiles;
create policy "profiles update own safe" on public.profiles for update using(id=auth.uid()) with check(id=auth.uid() and role='user');
drop policy if exists "articles public read" on public.articles;
create policy "articles public read" on public.articles for select using(published=true or public.is_admin());
drop policy if exists "articles admin insert" on public.articles;
create policy "articles admin insert" on public.articles for insert with check(public.is_admin());
drop policy if exists "articles admin update" on public.articles;
create policy "articles admin update" on public.articles for update using(public.is_admin()) with check(public.is_admin());
drop policy if exists "articles admin delete" on public.articles;
create policy "articles admin delete" on public.articles for delete using(public.is_admin());
drop policy if exists "orders own read" on public.orders;
create policy "orders own read" on public.orders for select using(user_id=auth.uid() or public.is_admin());
create policy "studio sessions own all" on public.studio_sessions for all using(user_id=auth.uid() or public.is_admin()) with check(user_id=auth.uid() or public.is_admin());
create policy "studio tracks own all" on public.studio_tracks for all using(user_id=auth.uid() or public.is_admin()) with check(user_id=auth.uid() or public.is_admin());
create policy "studio outputs own read" on public.studio_outputs for select using(user_id=auth.uid() or public.is_admin());
create policy "studio outputs admin manage" on public.studio_outputs for all using(public.is_admin()) with check(public.is_admin());
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin insert into public.profiles(id,email,role) values(new.id,new.email,'user'); return new; end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
-- Create a PRIVATE Storage bucket named studio-audio in Supabase Storage.
-- Storage object policies (run after bucket creation):
drop policy if exists "studio users upload own files" on storage.objects;
create policy "studio users upload own files" on storage.objects for insert to authenticated with check(bucket_id='studio-audio' and (storage.foldername(name))[1]=auth.uid()::text);
drop policy if exists "studio users read own files" on storage.objects;
create policy "studio users read own files" on storage.objects for select to authenticated using(bucket_id='studio-audio' and ((storage.foldername(name))[1]=auth.uid()::text or public.is_admin()));
drop policy if exists "studio users delete own files" on storage.objects;
create policy "studio users delete own files" on storage.objects for delete to authenticated using(bucket_id='studio-audio' and ((storage.foldername(name))[1]=auth.uid()::text or public.is_admin()));
